ORDER = ["car","house","person","bicycle","motorcycle","truck","boat",
         "sailboat","aircraft","wx","digipeater","igate","box","tower"]

def pack(grid):
    # normalise to 16x16
    g = [ (row + " "*16)[:16] for row in (grid + [" "*16]*16)[:16] ]
    on = lambda ch: ch not in (" ", ".")
    out = []
    for page in (0, 1):
        for x in range(16):
            b = 0
            for yy in range(8):
                y = page*8 + yy
                if on(g[y][x]):
                    b |= (1 << yy)
            out.append(b)
    return out, g

print("static const uint8_t ICON_BMP[%d][32] = {" % len(ORDER))
for i, name in enumerate(ORDER):
    bs, g = pack(ICONS[name])
    hexs = ", ".join("0x%02X" % b for b in bs)
    print("    { %s },  /* %2d %s */" % (hexs, i, name))
print("};")

print("\n/* preview")
for name in ORDER:
    _, g = pack(ICONS[name])
    print(name)
    for row in g:
        print("  " + row.replace(" ", ".").replace("x", "#").replace("@", "#"))
print("*/")
